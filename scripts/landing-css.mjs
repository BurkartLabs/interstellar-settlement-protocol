// Bug #4839: write public/landing.css, the part of public/styles.css the logged-out landing uses, so that only it blocks
// the landing's first paint and the whole stylesheet (190 KB, 40 KB compressed) loads beside it (public/index.html,
// public/scripts/appStyles.js). It is an extract, never a source: every rule is copied verbatim from styles.css, and
// tests/unit/landingCss.test.js fails when one no longer is. Edit styles.css, then run this again.
//
// What counts as used: Chromium's CSS coverage of the landing, logged out, at 375x812, 768x1024 and 1280x800, and at 375
// with reduced motion; plus the design tokens, the @font-face rules and any @keyframes a kept rule animates with.
//
// Run: `npm run css:landing` (it starts its own server on a port the OS picks).
import { chromium } from "playwright";
import { spawn } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import zlib from "node:zlib";
import { fileURLToPath } from "node:url";
import { cssRules, writeRules } from "./cssRules.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = path.join(ROOT, "public", "styles.css");
const OUT = path.join(ROOT, "public", "landing.css");
const VIEWS = [{ width: 375, height: 812 }, { width: 768, height: 1024 }, { width: 1280, height: 800 }, { width: 375, height: 812, reducedMotion: "reduce" }];

const css = fs.readFileSync(SOURCE, "utf8");
const rules = cssRules(css);
const dir = fs.mkdtempSync(path.join(os.tmpdir(), "isp-landing-css-"));
const server = spawn(process.execPath, ["server/index.js"], { cwd: ROOT, env: { ...process.env, ISP_DATA_DIR: dir, PORT: "0", NODE_ENV: "test", JWT_SECRET: "landing-css-scratch-secret-0123456789abcdef", ISP_DEV: "", ISP_DISABLE_TICKERS: "1" }, stdio: ["ignore", "pipe", "pipe"] });
const used = new Set();
try {
  const url = await new Promise((resolve, reject) => {
    let out = "";
    const timer = setTimeout(() => reject(new Error(`server did not listen: ${out}`)), 20_000);
    const read = (c) => { out += c; const m = out.match(/listening on port (\d+)/); if (m) { clearTimeout(timer); resolve(`http://127.0.0.1:${m[1]}`); } };
    server.stdout.on("data", read);
    server.stderr.on("data", read);
  });
  const browser = await chromium.launch();
  for (const { width, height, reducedMotion } of VIEWS) {
    const page = await browser.newPage({ viewport: { width, height }, reducedMotion: reducedMotion ?? "no-preference" });
    await page.coverage.startCSSCoverage();
    await page.goto(`${url}/`, { waitUntil: "networkidle" });
    await page.waitForTimeout(500);
    const entries = await page.coverage.stopCSSCoverage();
    const sheet = entries.find((e) => /\/styles\.css(\?|$)/.test(e.url));
    if (!sheet) throw new Error("the landing did not load styles.css");
    if (sheet.text !== css) throw new Error("the served styles.css is not the one on disk");
    rules.forEach((r, k) => { if (sheet.ranges.some((g) => g.start < r.end && g.end > r.start)) used.add(k); });
    await page.close();
  }
  await browser.close();
} finally { server.kill(); }

const always = (r) => /^@font-face\b/.test(r.prelude) || (r.context.length === 0 && r.prelude === ":root");
const kept = rules.filter((r, k) => used.has(k) || always(r));
const animations = new Set(kept.flatMap((r) => [...r.body.matchAll(/animation(?:-name)?\s*:\s*([^;]+)/g)].flatMap((m) => m[1].split(/[\s,]+/))));
const keyframes = rules.filter((r) => { const m = r.prelude.match(/^@keyframes\s+(\S+)/); return m && animations.has(m[1]); });
const extract = rules.filter((r) => kept.includes(r) || keyframes.includes(r)); // in source order, so the cascade holds

const header = `/* GENERATED by scripts/landing-css.mjs from styles.css (Bug #4839): the rules the logged-out landing uses, copied
   verbatim, so that only these block its first paint. Do not edit: change styles.css and run \`npm run css:landing\`.
   tests/unit/landingCss.test.js fails when a rule here is no longer in styles.css as written. */\n`;
const text = header + writeRules(extract);
fs.writeFileSync(OUT, text);
const gz = (s) => zlib.gzipSync(s).length;
console.log(`landing.css: ${extract.length} of ${rules.length} rules, ${(text.length / 1024).toFixed(1)} KB (${(gz(text) / 1024).toFixed(1)} KB gzip); styles.css ${(css.length / 1024).toFixed(1)} KB (${(gz(css) / 1024).toFixed(1)} KB gzip)`);
